BEGIN;
CREATE ROLE cve_migrator NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE cve_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
REVOKE ALL ON DATABASE cves FROM PUBLIC;
REVOKE ALL ON DATABASE postgres FROM PUBLIC;
REVOKE ALL ON DATABASE template1 FROM PUBLIC;
GRANT CONNECT ON DATABASE cves TO cve_migrator, cve_app;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA app AUTHORIZATION cve_migrator;
GRANT USAGE ON SCHEMA app TO cve_app;
ALTER ROLE cve_app IN DATABASE cves SET search_path TO pg_catalog, app;
ALTER ROLE cve_migrator IN DATABASE cves SET search_path TO pg_catalog, app;
ALTER ROLE cve_app IN DATABASE cves SET statement_timeout TO '10s';
ALTER DEFAULT PRIVILEGES FOR ROLE cve_migrator REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
COMMIT;
